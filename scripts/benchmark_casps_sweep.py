#!/usr/bin/env python3
"""Sweep a GPU's capacity: how many worlds fit at 1, 2, 4, ... agents per world.

For each agents-per-world level this finds the largest ``num_envs`` that actually
runs, and records CASPS (controlled agent steps per second) at every point it
visits, so you get both the memory ceiling and a throughput curve.

    PYTHONPATH=. python scripts/benchmark_casps_sweep.py --device cuda:0
    PYTHONPATH=. python scripts/benchmark_casps_sweep.py --device cuda:1 \
        --agents 1,2,4,8 --max-envs 2048 --out artifacts/casps_sweep

Results depend on the observation shape, so the observation settings of
``--base-config`` are recorded in the output and two sweeps are only comparable
when those match. This script does not vary them.

Notes on what "fits" means here:

* A trial must complete at least ``--iterations`` (default 2) PPO iterations.
  RSL-RL allocates its rollout storage and update buffers on the first learning
  step, so a run that builds its worlds fine can still die one iteration later.
  Counting a successful world build as "fits" overstates the ceiling.
* Each trial runs as a subprocess. A CUDA/PhysX out-of-memory can abort the
  process rather than raise, which would otherwise take the sweep down with it.
* At high agents-per-world the scene may not place every requested agent
  (``_scene_factory_spawn_valid``). CASPS is normalised by the agents that
  actually spawned, so rows where spawned < requested are flagged; do not read
  them as if every requested agent were live.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import os
import shutil
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass, asdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

DEFAULT_AGENT_LEVELS = [1, 2, 4, 8, 16, 32, 64]
# Substrings that identify an out-of-memory failure rather than a bug.
_OOM_PATTERNS = (
    "out of memory",
    "CUDA error: out of memory",
    "cudaErrorMemoryAllocation",
    "PxgCudaDeviceMemoryAllocator",
    "failed to allocate",
    "std::bad_alloc",
)


@dataclass
class Trial:
    agents_per_env: int
    num_envs: int
    verdict: str  # ok | oom | timeout | error
    casps: float | None = None
    env_steps_per_s: float | None = None
    spawned_agents: float | None = None
    requested_agents: int | None = None
    peak_vram_mib: int | None = None
    wall_s: float | None = None
    detail: str = ""

    @property
    def shortfall(self) -> bool:
        if self.spawned_agents is None or not self.requested_agents:
            return False
        return self.spawned_agents < 0.999 * self.requested_agents


