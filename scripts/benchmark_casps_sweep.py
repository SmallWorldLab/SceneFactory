def observation_summary(base_config: Path) -> dict:
    """Observation shape for the header — computed without touching a GPU."""
    try:
        import yaml
        from src.scene_factory_obs_contract import chocolate_observation_contract
    except Exception as exc:  # noqa: BLE001
        return {"error": f"could not compute: {exc}"}
    try:
        cfg = yaml.safe_load(base_config.read_text())
        obs = cfg.get("observation", {}) or {}
        contract = chocolate_observation_contract(
            road_points_enable=bool(obs.get("road_points_enable", True)),
            road_points_k=int(obs.get("road_points_k", 200)),
            road_points_include_dirs=bool(obs.get("road_points_include_dirs", False)),
            vehicle_obs_enable=bool(obs.get("neighbor_enable", True)),
            vehicle_obs_k=int(obs.get("neighbor_k", 63)),
            vehicle_obs_include_ttc=bool(obs.get("neighbor_include_ttc", False)),
        )
        return {
            "road_points_k": int(obs.get("road_points_k", 200)),
            "road_points_include_dirs": bool(obs.get("road_points_include_dirs", False)),
            "neighbor_k": int(obs.get("neighbor_k", 63)),
            "neighbor_include_ttc": bool(obs.get("neighbor_include_ttc", False)),
            "obs_dim_total": int(contract.total_dim),
        }
    except Exception as exc:  # noqa: BLE001
        return {"error": f"could not compute: {exc}"}


def write_outputs(out_dir: Path, trials: list[Trial], ceilings: dict[int, int | None], header: dict) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "sweep_meta.json").write_text(json.dumps(header, indent=2) + "\n")
    with (out_dir / "sweep_trials.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(asdict(trials[0]).keys()) if trials else ["agents_per_env"])
        w.writeheader()
        for t in trials:
            w.writerow(asdict(t))

    lines = [
        "agents/world | max worlds | agent slots | spawned | CASPS @ ceiling | best CASPS (@worlds) | peak VRAM",
        "-------------|------------|-------------|---------|-----------------|----------------------|----------",
    ]
    for a in sorted(ceilings):
        n = ceilings[a]
        at_ceiling = [t for t in trials if t.agents_per_env == a and t.num_envs == n and t.verdict == "ok"]
        oks = [t for t in trials if t.agents_per_env == a and t.verdict == "ok" and t.casps]
        best = max(oks, key=lambda t: t.casps) if oks else None
        c = at_ceiling[0] if at_ceiling else None
        lines.append(
            f"{a:>12} | {str(n):>10} | {str(a * n if n else '-'):>11} | "
            f"{(f'{c.spawned_agents:,.0f}' if c and c.spawned_agents else '-'):>7} | "
            f"{(f'{c.casps:,.0f}' if c and c.casps else '-'):>15} | "
            f"{(f'{best.casps:,.0f} (@{best.num_envs})' if best else '-'):>20} | "
            f"{(f'{c.peak_vram_mib} MiB' if c and c.peak_vram_mib else '-'):>9}"
        )
    flagged = sorted({t.agents_per_env for t in trials if t.shortfall})
    if flagged:
        lines.append("")
        lines.append(
            "NOTE: at agents/world = "
            + ", ".join(str(a) for a in flagged)
            + " the scene did not place every requested agent. CASPS is normalised by "
              "agents that actually spawned, so these rows do not represent the "
              "requested agent count."
        )
    table = "\n".join(lines)
    (out_dir / "sweep_summary.txt").write_text(table + "\n")
    print("\n" + table)


