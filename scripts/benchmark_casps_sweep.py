def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--device", default="cuda:0", help="target device, e.g. cuda:1")
    p.add_argument("--agents", default=",".join(str(a) for a in DEFAULT_AGENT_LEVELS),
                   help="comma-separated agents-per-world levels")
    p.add_argument("--base-config", type=Path,
                   default=REPO_ROOT / "configs/scene_factory/demo_weather_physx_train.yaml",
                   help="config supplying observation/reward/policy settings")
    p.add_argument("--scene-json", default="scene_000077.json",
                   help="single scene replicated to every world")
    p.add_argument("--scene-dir", default="data/processed/waymo_scenes_json")
    p.add_argument("--out", type=Path, default=REPO_ROOT / "artifacts/casps_sweep")
    p.add_argument("--min-envs", type=int, default=8)
    p.add_argument("--max-envs", type=int, default=8192)
    p.add_argument("--seed-envs", type=int, default=256,
                   help="starting guess for the first (lowest) agent level")
    p.add_argument("--iterations", type=int, default=2,
                   help="PPO iterations per SEARCH trial; >=2 so the update path allocates. "
                        "Search trials only need pass/fail, so keep this small.")
    p.add_argument("--measure-iterations", type=int, default=12,
                   help="PPO iterations for the confirmation run at each ceiling, from which "
                        "the reported CASPS is taken. 0 disables the confirmation pass.")
    p.add_argument("--warmup-iterations", type=int, default=4,
                   help="leading iterations discarded from the confirmation run; the first "
                        "absorbs CUDA context creation, kernel autotune and Fabric settling")
    p.add_argument("--timeout", type=float, default=1800.0, help="per-trial seconds")
    p.add_argument("--heartbeat", type=float, default=30.0,
                   help="seconds between progress lines while a trial runs (0 disables). "
                        "A trial is an Isaac Sim boot plus a world build and can take many "
                        "minutes before it prints a result.")
    p.add_argument("--keep-logs", action="store_true",
                   help="keep per-trial stdout/stderr logs under --out instead of discarding")
    p.add_argument("--tolerance", type=float, default=0.12,
                   help="stop bisecting at this relative bracket width")
    p.add_argument("--force", action="store_true",
                   help="run even if the target GPU is already in use")
    p.add_argument("--dry-run", action="store_true",
                   help="simulate trials (no GPU, no Isaac Sim) to check the plan")
    p.add_argument("--sim-budget", type=int, default=40000,
                   help="--dry-run only: pretend the device holds this many agent slots")
    args = p.parse_args()

    levels = [int(x) for x in args.agents.split(",") if x.strip()]
    idx = gpu_index(args.device)

    used, total = gpu_free_mib(idx)
    if not args.dry_run:
        if used < 0:
            print("WARNING: could not query nvidia-smi; VRAM will not be reported.")
        elif used > 0.15 * total and not args.force:
            print(
                f"REFUSING to start: GPU {idx} already has {used} MiB of {total} MiB in use.\n"
                "A capacity sweep deliberately drives the device to OOM and would disrupt "
                "that work.\nUse --force to override, or pick another --device.",
                file=sys.stderr,
            )
            return 2

    obs = observation_summary(args.base_config)
    header = {
        "device": args.device,
        "gpu_total_mib": total,
        "base_config": str(args.base_config),
        "scene_json": args.scene_json,
        "iterations_per_trial": args.iterations,
        "agent_levels": levels,
        "observation": obs,
        "dry_run": bool(args.dry_run),
    }
    print(json.dumps(header, indent=2))
    print("\nObservation settings are fixed for this sweep; results are only "
          "comparable across sweeps with the same 'observation' block above.\n")

    workdir = Path(tempfile.mkdtemp(prefix="casps_sweep_"))
    trials: list[Trial] = []
    ceilings: dict[int, int | None] = {}
    measured: dict[int, Trial] = {}
    try:
        seed = args.seed_envs
        for a in levels:
            print(f"  agents/world = {a}  (seed {seed})", flush=True)
            ceiling = sweep_agent_level(a, seed_envs=seed, args=args, workdir=workdir, trials=trials)
            ceilings[a] = ceiling
            print(f"  -> ceiling for {a} agents/world: {ceiling}", flush=True)

            # The search trials run only --iterations (default 2) and so give a
            # single post-warmup CASPS sample. Re-run once at the ceiling for a
            # longer, warmup-trimmed measurement, and prefer that number.
            if ceiling and args.measure_iterations > 0 and not args.dry_run:
                warm = min(args.warmup_iterations, max(0, args.measure_iterations - 1))
                print(
                    f"     confirming CASPS at {ceiling} worlds "
                    f"({args.measure_iterations} iters, first {warm} discarded)...",
                    flush=True,
                )
                m = run_trial(
                    agents_per_env=a, num_envs=ceiling, args=args, workdir=workdir,
                    iterations=args.measure_iterations, warmup_iters=warm, tag="_measure",
                )
                m.detail = (m.detail + " | confirmation run").strip(" |")
                measured[a] = m
                trials.append(m)
                casps = f"{m.casps:,.0f}" if m.casps else "-"
                print(f"     confirmed: {m.verdict}  CASPS={casps}", flush=True)
            print("", flush=True)
            # Memory scales roughly with total agent slots, so the next level
            # (2x agents) should land near half the worlds.
            seed = max(args.min_envs, (ceiling or seed) // 2)
    finally:
        if trials:
            write_outputs(args.out, trials, ceilings, header, measured)
        # Preserve logs for anything that did not pass, so a failure is debuggable
        # after the temp dir goes away.
        keep = args.keep_logs or any(t.verdict != "ok" for t in trials)
        if keep and not args.dry_run:
            dest = args.out / "trial_logs"
            dest.mkdir(parents=True, exist_ok=True)
            for f in list(workdir.glob("*.log")) + list(workdir.glob("*.err")):
                try:
                    shutil.copy2(f, dest / f.name)
                except OSError:
                    pass
            print(f"\n[logs] per-trial stdout/stderr copied to {dest}")
        shutil.rmtree(workdir, ignore_errors=True)
    return 0


