#!/usr/bin/env python3
"""Sweep a GPU's capacity: how many worlds fit at 1, 2, 4, ... agents per world.

For each agents-per-world level this finds the largest ``num_envs`` that actually
runs, and records CASPS (controlled agent steps per second) at every point it
visits, so you get both the memory ceiling and a throughput curve.

    PYTHONPATH=. python scripts/benchmark_casps_sweep.py --device cuda:0
    PYTHONPATH=. python scripts/benchmark_casps_sweep.py --device cuda:1 \
        --agents 1,2,4,8 --max-envs 2048 --out artifacts/casps_sweep

Results depend on the observation shape, so the observation settings of
``--base-config`` are recorded in the output and two sweeps are only comparable
when those match. This script does not vary them.

Notes on what "fits" means here:

* A trial must complete at least ``--iterations`` (default 2) PPO iterations.
  RSL-RL allocates its rollout storage and update buffers on the first learning
  step, so a run that builds its worlds fine can still die one iteration later.
  Counting a successful world build as "fits" overstates the ceiling.
* Each trial runs as a subprocess. A CUDA/PhysX out-of-memory can abort the
  process rather than raise, which would otherwise take the sweep down with it.
* At high agents-per-world the scene may not place every requested agent
  (``_scene_factory_spawn_valid``). CASPS is normalised by the agents that
  actually spawned, so rows where spawned < requested are flagged; do not read
  them as if every requested agent were live.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import os
import shutil
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass, asdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

DEFAULT_AGENT_LEVELS = [1, 2, 4, 8, 16, 32, 64]
# Substrings that identify an out-of-memory failure rather than a bug.
_OOM_PATTERNS = (
    "out of memory",
    "CUDA error: out of memory",
    "cudaErrorMemoryAllocation",
    "PxgCudaDeviceMemoryAllocator",
    "failed to allocate",
    "std::bad_alloc",
)


@dataclass
class Trial:
    agents_per_env: int
    num_envs: int
    verdict: str  # ok | oom | timeout | error
    casps: float | None = None
    env_steps_per_s: float | None = None
    spawned_agents: float | None = None
    requested_agents: int | None = None
    peak_vram_mib: int | None = None
    wall_s: float | None = None
    detail: str = ""

    @property
    def shortfall(self) -> bool:
        if self.spawned_agents is None or not self.requested_agents:
            return False
        return self.spawned_agents < 0.999 * self.requested_agents


# --------------------------------------------------------------------------- #
# scene pool generation
# --------------------------------------------------------------------------- #

def _grid_for(world_count: int) -> tuple[int, int]:
    """Near-square grid, cols >= rows, cols*rows >= world_count."""
    cols = int(math.ceil(math.sqrt(world_count)))
    rows = int(math.ceil(world_count / cols))
    return cols, rows


def write_scene_pool(path: Path, *, world_count: int, scene_json: str, scene_dir: str) -> None:
    """One scene replicated to every world, mirroring the *_stress_* pools.

    Uses assignment_fill_mode: random_fill so a single assignment entry expands
    to world_count worlds.
    """
    cols, rows = _grid_for(world_count)
    path.write_text(
        "# Generated by scripts/benchmark_casps_sweep.py — do not edit.\n"
        f"# Single scene replicated to {world_count} worlds for throughput measurement.\n"
        "io:\n"
        f"  scene_json_dir: {scene_dir}\n"
        "world:\n"
        "  root_container: /World/SceneFactoryWorlds\n"
        f"  world_count: {world_count}\n"
        f"  grid_cols: {cols}\n"
        f"  rows: {rows}\n"
        "  world_size_m: [200.0, 200.0]\n"
        "  padding_m: 200.0\n"
        "  base_z_m: 0.0\n"
        "  bounds_size_m: 200.0\n"
        "  origin_mode: center\n"
        "  origin_center_mode: mean\n"
        "  assignment_fill_mode: random_fill\n"
        "  assignment_fill_seed: 2024\n"
        "  assignments:\n"
        f"  - scene_json: {scene_json}\n"
        "    friction: {road_type: AC, precip_type: clear, precip_intensity_mmph: 0.0, water_film_mm: 0.0}\n"
    )


# --------------------------------------------------------------------------- #
# result harvesting
# --------------------------------------------------------------------------- #

def read_casps_from_tensorboard(log_dir: Path) -> tuple[float | None, float | None, float | None]:
    """Return (max CASPS, env_steps_per_s at that point, spawned agent count).

    CASPS is only emitted to TensorBoard (Perf/CASPS) by the RSL-RL wrapper; it
    is not printed to stdout.
    """
    try:
        from tensorboard.backend.event_processing import event_accumulator
    except ImportError:
        return None, None, None

    events = sorted(log_dir.rglob("events.out.tfevents.*"))
    if not events:
        return None, None, None

    best_casps: float | None = None
    best_steps: float | None = None
    spawned: float | None = None
    for ev in events:
        try:
            acc = event_accumulator.EventAccumulator(
                str(ev), size_guidance={event_accumulator.SCALARS: 0}
            )
            acc.Reload()
            tags = set(acc.Tags().get("scalars", []))
            if "Perf/CASPS" in tags:
                for s in acc.Scalars("Perf/CASPS"):
                    if best_casps is None or s.value > best_casps:
                        best_casps = float(s.value)
            if "Perf/env_steps_per_s" in tags:
                vals = [s.value for s in acc.Scalars("Perf/env_steps_per_s")]
                if vals:
                    best_steps = float(max(vals))
            if "Perf/controlled_agent_count" in tags:
                vals = [s.value for s in acc.Scalars("Perf/controlled_agent_count")]
                if vals:
                    spawned = float(vals[-1])
        except Exception:  # noqa: BLE001 - a partial event file is not fatal
            continue
    return best_casps, best_steps, spawned


def classify_failure(stdout: str, stderr: str, returncode: int) -> tuple[str, str]:
    blob = f"{stdout}\n{stderr}"
    low = blob.lower()
    for pat in _OOM_PATTERNS:
        if pat.lower() in low:
            return "oom", pat
    tail = [ln for ln in blob.strip().splitlines() if ln.strip()][-1:] or [""]
    return "error", f"rc={returncode}: {tail[0][:200]}"


# --------------------------------------------------------------------------- #
# a single trial
# --------------------------------------------------------------------------- #

def gpu_index(device: str) -> int:
    if ":" in device:
        return int(device.split(":")[1])
    return 0


def gpu_free_mib(index: int) -> tuple[int, int]:
    try:
        out = subprocess.run(
            ["nvidia-smi", f"--id={index}", "--query-gpu=memory.used,memory.total",
             "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=30, check=True,
        ).stdout.strip()
        used, total = (int(x.strip()) for x in out.split(","))
        return used, total
    except Exception:  # noqa: BLE001
        return -1, -1


def run_trial(
    *,
    agents_per_env: int,
    num_envs: int,
    args: argparse.Namespace,
    workdir: Path,
) -> Trial:
    if args.dry_run:
        return _simulated_trial(agents_per_env, num_envs, args)

    idx = gpu_index(args.device)
    pool = workdir / f"pool_a{agents_per_env}_n{num_envs}.yaml"
    write_scene_pool(
        pool,
        world_count=num_envs,
        scene_json=args.scene_json,
        scene_dir=args.scene_dir,
    )
    log_dir = workdir / f"logs_a{agents_per_env}_n{num_envs}"

    cmd = [
        sys.executable, "-u", "src/train_student_vehicle_goal_multiagent_rsl_rl.py",
        "--config", str(args.base_config),
        "--headless",
        "--num_envs", str(num_envs),
        "--num_agents_per_env", str(agents_per_env),
        "--scene_factory_config", str(pool),
        "--max_iterations", str(args.iterations),
        "--log_dir", str(log_dir),
        "--experiment_name", "casps_sweep",
        "--run_name", f"a{agents_per_env}_n{num_envs}",
        "--save_interval", str(10 ** 6),  # never checkpoint during a benchmark
        "--step_timing_log_enable",
    ]

    env = os.environ.copy()
    # Isolate: the child sees only the target GPU, and addresses it as cuda:0.
    env["CUDA_VISIBLE_DEVICES"] = str(idx)
    env["PYTHONPATH"] = str(REPO_ROOT)

    started = time.time()
    peak_vram = [0]
    try:
        proc = subprocess.Popen(
            cmd, cwd=str(REPO_ROOT), env=env,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
        )
        # Poll VRAM while it runs; PhysX/USD allocate outside torch, so
        # torch.cuda counters would undercount badly.
        while proc.poll() is None:
            used, _ = gpu_free_mib(idx)
            if used > peak_vram[0]:
                peak_vram[0] = used
            if time.time() - started > args.timeout:
                proc.kill()
                proc.wait(timeout=60)
                return Trial(
                    agents_per_env, num_envs, "timeout",
                    requested_agents=agents_per_env * num_envs,
                    peak_vram_mib=peak_vram[0] or None,
                    wall_s=time.time() - started,
                    detail=f"exceeded --timeout {args.timeout}s",
                )
            time.sleep(2.0)
        stdout, stderr = proc.communicate(timeout=120)
        rc = proc.returncode
    except Exception as exc:  # noqa: BLE001
        return Trial(
            agents_per_env, num_envs, "error",
            requested_agents=agents_per_env * num_envs,
            wall_s=time.time() - started, detail=f"launch failed: {exc}",
        )

    wall = time.time() - started
    if rc != 0:
        verdict, detail = classify_failure(stdout, stderr, rc)
        return Trial(
            agents_per_env, num_envs, verdict,
            requested_agents=agents_per_env * num_envs,
            peak_vram_mib=peak_vram[0] or None, wall_s=wall, detail=detail,
        )

    casps, steps_s, spawned = read_casps_from_tensorboard(log_dir)
    return Trial(
        agents_per_env, num_envs, "ok",
        casps=casps, env_steps_per_s=steps_s, spawned_agents=spawned,
        requested_agents=agents_per_env * num_envs,
        peak_vram_mib=peak_vram[0] or None, wall_s=wall,
        detail="" if casps is not None else "ran, but no Perf/CASPS scalar found",
    )


def _simulated_trial(agents_per_env: int, num_envs: int, args: argparse.Namespace) -> Trial:
    """Fake trial for --dry-run: exercises search/report logic without a GPU."""
    budget = args.sim_budget  # pretend total agent slots the device can hold
    slots = agents_per_env * num_envs
    requested = slots
    if slots > budget:
        return Trial(agents_per_env, num_envs, "oom", requested_agents=requested,
                     wall_s=1.0, detail="simulated")
    # Pretend the scene can only place ~12 agents per world.
    spawned = float(num_envs * min(agents_per_env, 12))
    casps = spawned * (900.0 / (1.0 + num_envs / 512.0)) / 1000.0
    return Trial(agents_per_env, num_envs, "ok", casps=casps,
                 env_steps_per_s=900.0 / (1.0 + num_envs / 512.0),
                 spawned_agents=spawned, requested_agents=requested,
                 peak_vram_mib=int(slots * 23 / 1024), wall_s=1.0,
                 detail="simulated")


# --------------------------------------------------------------------------- #
# search
# --------------------------------------------------------------------------- #

def sweep_agent_level(
    agents_per_env: int,
    *,
    seed_envs: int,
    args: argparse.Namespace,
    workdir: Path,
    trials: list[Trial],
) -> int | None:
    """Coarse seeded search for the largest num_envs that runs.

    Ramps from a seed (previous level's answer, halved), doubling until failure,
    then bisects until the bracket is within --tolerance relative width.
    Returns the largest known-good num_envs, or None.
    """
    def attempt(n: int) -> Trial:
        n = max(args.min_envs, min(args.max_envs, int(n)))
        t = run_trial(agents_per_env=agents_per_env, num_envs=n, args=args, workdir=workdir)
        trials.append(t)
        flag = "  <-- spawned < requested" if t.shortfall else ""
        casps = f"{t.casps:,.0f}" if t.casps else "-"
        print(
            f"    agents={agents_per_env:>3}  envs={n:>6}  {t.verdict:<7} "
            f"CASPS={casps:>10}  vram={t.peak_vram_mib or '-'} MiB  "
            f"({t.wall_s:.0f}s){flag}",
            flush=True,
        )
        return t

    good: int | None = None
    bad: int | None = None

    n = max(args.min_envs, min(args.max_envs, seed_envs))
    t = attempt(n)
    if t.verdict == "ok":
        good = n
        while good is not None and good < args.max_envs:
            nxt = min(good * 2, args.max_envs)
            if nxt == good:
                break
            t = attempt(nxt)
            if t.verdict == "ok":
                good = nxt
            else:
                bad = nxt
                break
    else:
        bad = n
        while bad is not None and bad > args.min_envs:
            nxt = max(bad // 2, args.min_envs)
            t = attempt(nxt)
            if t.verdict == "ok":
                good = nxt
                break
            bad = nxt
            if nxt == args.min_envs:
                break

    # Bisect the bracket.
    while good is not None and bad is not None and (bad - good) > max(1, int(good * args.tolerance)):
        mid = (good + bad) // 2
        if mid in (good, bad):
            break
        t = attempt(mid)
        if t.verdict == "ok":
            good = mid
        else:
            bad = mid
    return good


