def _tail_line(path: Path, *, max_len: int = 110) -> str:
    """Last non-empty line of a growing log, for heartbeat output."""
    try:
        lines = [ln.strip() for ln in path.read_text(errors="replace").splitlines() if ln.strip()]
    except OSError:
        return ""
    if not lines:
        return "(no output yet)"
    line = lines[-1]
    return line[:max_len] + ("..." if len(line) > max_len else "")


def gpu_index(device: str) -> int:
    if ":" in device:
        return int(device.split(":")[1])
    return 0


def gpu_free_mib(index: int) -> tuple[int, int]:
    try:
        out = subprocess.run(
            ["nvidia-smi", f"--id={index}", "--query-gpu=memory.used,memory.total",
             "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=30, check=True,
        ).stdout.strip()
        used, total = (int(x.strip()) for x in out.split(","))
        return used, total
    except Exception:  # noqa: BLE001
        return -1, -1


def run_trial(
    *,
    agents_per_env: int,
    num_envs: int,
    args: argparse.Namespace,
    workdir: Path,
    iterations: int | None = None,
    warmup_iters: int = 0,
    tag: str = "",
) -> Trial:
    if args.dry_run:
        return _simulated_trial(agents_per_env, num_envs, args)

    iterations = int(iterations if iterations is not None else args.iterations)

    idx = gpu_index(args.device)
    pool = workdir / f"pool_a{agents_per_env}_n{num_envs}.yaml"
    write_scene_pool(
        pool,
        world_count=num_envs,
        scene_json=args.scene_json,
        scene_dir=args.scene_dir,
    )
    log_dir = workdir / f"logs_a{agents_per_env}_n{num_envs}{tag}"

    cmd = [
        sys.executable, "-u", "src/train_student_vehicle_goal_multiagent_rsl_rl.py",
        "--config", str(args.base_config),
        "--headless",
        "--num_envs", str(num_envs),
        "--num_agents_per_env", str(agents_per_env),
        "--scene_factory_config", str(pool),
        "--max_iterations", str(iterations),
        "--log_dir", str(log_dir),
        "--experiment_name", "casps_sweep",
        "--run_name", f"a{agents_per_env}_n{num_envs}{tag}",
        "--save_interval", str(10 ** 6),  # never checkpoint during a benchmark
        "--step_timing_log_enable",
    ]

    env = os.environ.copy()
    # Isolate: the child sees only the target GPU, and addresses it as cuda:0.
    env["CUDA_VISIBLE_DEVICES"] = str(idx)
    env["PYTHONPATH"] = str(REPO_ROOT)

    started = time.time()
    trial_timeout = args.timeout + args.timeout_per_env * num_envs
    peak_vram = 0
    # Isaac Sim emits far more than a pipe buffer holds during startup. Capturing
    # to subprocess.PIPE without draining it deadlocks the child on write, so the
    # streams go to files and are read back after exit.
    out_path = workdir / f"trial_a{agents_per_env}_n{num_envs}{tag}.log"
    err_path = workdir / f"trial_a{agents_per_env}_n{num_envs}{tag}.err"
    last_beat = started
    try:
        with out_path.open("w") as fout, err_path.open("w") as ferr:
            proc = subprocess.Popen(
                cmd, cwd=str(REPO_ROOT), env=env, stdout=fout, stderr=ferr, text=True,
            )
            # Poll VRAM while it runs; PhysX/USD allocate outside torch, so
            # torch.cuda counters would undercount badly.
            while proc.poll() is None:
                used, _ = gpu_free_mib(idx)
                if used > peak_vram:
                    peak_vram = used
                now = time.time()
                if args.heartbeat > 0 and (now - last_beat) >= args.heartbeat:
                    last_beat = now
                    print(
                        f"        ... {now - started:5.0f}s  vram={used if used >= 0 else '?'} MiB"
                        f"  | {_tail_line(out_path)}",
                        flush=True,
                    )
                if now - started > trial_timeout:
                    proc.kill()
                    proc.wait(timeout=60)
                    return Trial(
                        agents_per_env, num_envs, "timeout",
                        requested_agents=agents_per_env * num_envs,
                        peak_vram_mib=peak_vram or None,
                        wall_s=time.time() - started,
                        detail=f"exceeded timeout {trial_timeout:.0f}s; see {out_path}",
                    )
                time.sleep(2.0)
            rc = proc.returncode
        stdout = out_path.read_text(errors="replace")
        stderr = err_path.read_text(errors="replace")
    except Exception as exc:  # noqa: BLE001
        return Trial(
            agents_per_env, num_envs, "error",
            requested_agents=agents_per_env * num_envs,
            wall_s=time.time() - started, detail=f"launch failed: {exc}",
        )

    wall = time.time() - started
    if rc != 0:
        verdict, detail = classify_failure(stdout, stderr, rc)
        return Trial(
            agents_per_env, num_envs, verdict,
            requested_agents=agents_per_env * num_envs,
            peak_vram_mib=peak_vram or None, wall_s=wall, detail=detail,
        )

    casps, steps_s, spawned = read_casps_from_tensorboard(log_dir, warmup_iters=warmup_iters)
    iters = iterations_completed(stdout)

    # Exit code 0 is NOT sufficient. Isaac Sim can fail during setup and still
    # exit cleanly, which previously produced a passing trial that had never
    # trained -- inflating the ceiling and burning ~30 min per doomed trial.
    # A pass must show the requested iterations AND a CASPS scalar.
    if iters < iterations or casps is None:
        return Trial(
            agents_per_env, num_envs, "incomplete",
            casps=casps, env_steps_per_s=steps_s, spawned_agents=spawned,
            requested_agents=agents_per_env * num_envs,
            peak_vram_mib=peak_vram or None, wall_s=wall,
            detail=(
                f"exit 0 but only {iters}/{iterations} iterations announced"
                + ("" if casps is not None else " and no Perf/CASPS scalar")
                + f"; see {out_path.name}"
            ),
        )

    return Trial(
        agents_per_env, num_envs, "ok",
        casps=casps, env_steps_per_s=steps_s, spawned_agents=spawned,
        requested_agents=agents_per_env * num_envs,
        peak_vram_mib=peak_vram or None, wall_s=wall,
    )


def _simulated_trial(agents_per_env: int, num_envs: int, args: argparse.Namespace) -> Trial:
    """Fake trial for --dry-run: exercises search/report logic without a GPU."""
    budget = args.sim_budget  # pretend total agent slots the device can hold
    slots = agents_per_env * num_envs
    requested = slots
    if slots > budget:
        return Trial(agents_per_env, num_envs, "oom", requested_agents=requested,
                     wall_s=1.0, detail="simulated")
    # Pretend the scene can only place ~12 agents per world.
    spawned = float(num_envs * min(agents_per_env, 12))
    casps = spawned * (900.0 / (1.0 + num_envs / 512.0)) / 1000.0
    return Trial(agents_per_env, num_envs, "ok", casps=casps,
                 env_steps_per_s=900.0 / (1.0 + num_envs / 512.0),
                 spawned_agents=spawned, requested_agents=requested,
                 peak_vram_mib=int(3151 + 5.23 * num_envs + 1.9 * slots), wall_s=1.0,
                 detail="simulated")


# --------------------------------------------------------------------------- #
# memory model
# --------------------------------------------------------------------------- #

def fit_vram_model(samples: list[tuple[int, int]]) -> tuple[float, float] | None:
    """Least-squares fit of peak VRAM (MiB) against num_envs.

    Measured VRAM is strikingly linear in world count -- on a 4090 at 1
    agent/world the observed slope was 5.24 MiB/env with a 3.1 GB intercept
    across 256..2048 worlds. That makes the ceiling predictable from a couple of
    small, cheap trials instead of found by doubling into 30-minute failures.
    """
    pts = [(n, v) for n, v in samples if n > 0 and v and v > 0]
    if len(pts) < 2:
        return None
    n_mean = sum(n for n, _ in pts) / len(pts)
    v_mean = sum(v for _, v in pts) / len(pts)
    denom = sum((n - n_mean) ** 2 for n, _ in pts)
    if denom <= 0:
        return None
    slope = sum((n - n_mean) * (v - v_mean) for n, v in pts) / denom
    if slope <= 0:
        return None
    return slope, v_mean - slope * n_mean


def predict_max_envs(model: tuple[float, float], budget_mib: float) -> int:
    slope, intercept = model
    return max(1, int((budget_mib - intercept) / slope))


def fit_global_vram_model(
    samples: list[tuple[int, int, int]],
) -> tuple[float, float, float] | None:
    """Fit VRAM(N, A) = c0 + c_w*N + c_a*(N*A) over all agent levels at once.

    Separates the per-world cost (roads, USD prims, ground) from the per-agent
    cost (articulation, observation and rollout buffers), so a handful of small
    cheap trials predicts the ceiling for EVERY agent level without searching
    each one. Needs >= 3 samples spanning at least two distinct N*A values.
    """
    pts = [(n, a, v) for n, a, v in samples if n > 0 and a > 0 and v and v > 0]
    if len(pts) < 3:
        return None
    try:
        import numpy as np
    except ImportError:
        return None
    A = np.array([[1.0, float(n), float(n * a)] for n, a, _ in pts])
    y = np.array([float(v) for _, _, v in pts])
    if np.linalg.matrix_rank(A) < 3:
        return None
    coef, *_ = np.linalg.lstsq(A, y, rcond=None)
    c0, c_w, c_a = (float(x) for x in coef)
    if c_w + c_a <= 0:
        return None
    return c0, c_w, c_a


def predict_max_envs_for_agents(
    model: tuple[float, float, float], agents: int, budget_mib: float
) -> int:
    c0, c_w, c_a = model
    denom = c_w + c_a * agents
    if denom <= 0:
        return 1
    return max(1, int((budget_mib - c0) / denom))


def calibrate(
    args: argparse.Namespace, workdir: Path, trials: list[Trial], levels: list[int]
) -> list[tuple[int, int, int]]:
    """Cheap small trials spanning (N, A), used to fit the global model.

    Every probe is deliberately small: trial cost is linear in world count, so
    calibration is nearly free compared with a single probe near the ceiling.
    """
    lo, hi = min(levels), max(levels)
    plan = [
        (args.calib_envs, lo),
        (args.calib_envs * 2, lo),
        (args.calib_envs * 4, lo),
        (args.calib_envs * 2, hi),
    ]
    if len(levels) > 2:
        plan.append((args.calib_envs * 2, levels[len(levels) // 2]))

    print(f"  calibration: {len(plan)} small trials to fit the memory model", flush=True)
    samples: list[tuple[int, int, int]] = []
    for n, a in plan:
        n = max(args.min_envs, min(args.max_envs, n))
        tr = run_trial(agents_per_env=a, num_envs=n, args=args, workdir=workdir, tag="_calib")
        trials.append(tr)
        casps = f"{tr.casps:,.0f}" if tr.casps else "-"
        print(
            f"    calib agents={a:>3} envs={n:>5}  {tr.verdict:<10} "
            f"vram={tr.peak_vram_mib or '-'} MiB  CASPS={casps}  ({tr.wall_s:.0f}s)",
            flush=True,
        )
        if tr.verdict == "ok" and tr.peak_vram_mib:
            samples.append((n, a, tr.peak_vram_mib))
    return samples


# --------------------------------------------------------------------------- #
# search
# --------------------------------------------------------------------------- #

def sweep_agent_level(
    agents_per_env: int,
    *,
    seed_envs: int,
    args: argparse.Namespace,
    workdir: Path,
    trials: list[Trial],
    budget_mib: float = 0.0,
) -> int | None:
    """Coarse seeded search for the largest num_envs that runs.

    Ramps from a seed (previous level's answer, halved), doubling until failure,
    then bisects until the bracket is within --tolerance relative width.
    Returns the largest known-good num_envs, or None.
    """
    def attempt(n: int) -> Trial:
        n = max(args.min_envs, min(args.max_envs, int(n)))
        t = run_trial(agents_per_env=agents_per_env, num_envs=n, args=args, workdir=workdir)
        trials.append(t)
        flag = "  <-- spawned < requested" if t.shortfall else ""
        casps = f"{t.casps:,.0f}" if t.casps else "-"
        print(
            f"    agents={agents_per_env:>3}  envs={n:>6}  {t.verdict:<7} "
            f"CASPS={casps:>10}  vram={t.peak_vram_mib or '-'} MiB  "
            f"({t.wall_s:.0f}s){flag}",
            flush=True,
        )
        return t

    good: int | None = None
    bad: int | None = None
    samples: list[tuple[int, int]] = []

    def note(tr: Trial) -> None:
        if tr.verdict == "ok" and tr.peak_vram_mib:
            samples.append((tr.num_envs, tr.peak_vram_mib))

    n = max(args.min_envs, min(args.max_envs, seed_envs))
    t = attempt(n)
    note(t)
    if t.verdict == "ok":
        good = n
        while good is not None and good < args.max_envs:
            # Prefer a model-predicted jump over blind doubling: build time is
            # linear in world count (~0.23 s/world measured), so overshooting is
            # the most expensive mistake available.
            model = fit_vram_model(samples)
            nxt = min(good * 2, args.max_envs)
            if model and budget_mib > 0:
                pred = predict_max_envs(model, budget_mib)
                if pred <= good:
                    # Model says we are already at the ceiling; probe just above
                    # to confirm rather than doubling.
                    nxt = min(int(good * 1.15) + 1, args.max_envs)
                else:
                    nxt = min(max(pred, good + 1), good * 2, args.max_envs)
                print(
                    f"      [model] {model[1]:.0f} + {model[0]:.2f}/env  ->  "
                    f"predicted ceiling {pred} envs; probing {nxt}",
                    flush=True,
                )
            if nxt <= good:
                break
            t = attempt(nxt)
            note(t)
            if t.verdict == "ok":
                good = nxt
            else:
                bad = nxt
                break
    else:
        bad = n
        while bad is not None and bad > args.min_envs:
            nxt = max(bad // 2, args.min_envs)
            t = attempt(nxt)
            note(t)
            if t.verdict == "ok":
                good = nxt
                break
            bad = nxt
            if nxt == args.min_envs:
                break

    # Bisect the bracket.
    while good is not None and bad is not None and (bad - good) > max(1, int(good * args.tolerance)):
        mid = (good + bad) // 2
        if mid in (good, bad):
            break
        t = attempt(mid)
        note(t)
        if t.verdict == "ok":
            good = mid
        else:
            bad = mid
    return good


def run_model_mode(
    args: argparse.Namespace,
    workdir: Path,
    trials: list[Trial],
    levels: list[int],
    budget_mib: float,
    ceilings: dict[int, int | None],
    measured: dict[int, Trial],
) -> None:
    """Calibrate once, solve each level, confirm with one trial.

    Trial cost is linear in world count, so the expensive probes are the ones
    near the ceiling. Rather than searching for each level, fit VRAM(N, A) from
    cheap small trials and solve. Levels run cheapest-first (highest agents ->
    fewest worlds) so every confirmation refines the model before the costly
    low-agent levels are attempted.
    """
    samples = calibrate(args, workdir, trials, levels)
    model = fit_global_vram_model(samples)
    if model is None:
        print("  [model] calibration failed; falling back to search mode\n", flush=True)
        seed = args.seed_envs
        for a in levels:
            ceilings[a] = sweep_agent_level(
                a, seed_envs=seed, args=args, workdir=workdir,
                trials=trials, budget_mib=budget_mib,
            )
            seed = max(args.min_envs, (ceilings[a] or seed) // 2)
        return

    c0, c_w, c_a = model
    print(
        f"\n  [model] VRAM(N,A) = {c0:.0f} + {c_w:.2f}*N + {c_a:.2f}*N*A  MiB"
        f"   (budget {budget_mib:.0f} MiB)",
        flush=True,
    )
    for a in levels:
        print(f"          agents={a:>3} -> predicted ceiling "
              f"{predict_max_envs_for_agents(model, a, budget_mib):>6} worlds", flush=True)
    print("", flush=True)

    # Cheapest first: high agents/world needs the fewest worlds.
    for a in sorted(levels, reverse=True):
        pred = predict_max_envs_for_agents(model, a, budget_mib)
        # Undershoot deliberately. A pass yields the ceiling AND the CASPS
        # measurement; an overshoot costs a full expensive trial for a "no".
        target = max(args.min_envs, min(args.max_envs, int(pred * args.undershoot)))
        print(f"  agents/world = {a}: predicted {pred}, confirming at {target}", flush=True)

        warm = min(args.warmup_iterations, max(0, args.measure_iterations - 1))
        iters = args.measure_iterations if args.measure_iterations > 0 else args.iterations
        tr = run_trial(
            agents_per_env=a, num_envs=target, args=args, workdir=workdir,
            iterations=iters, warmup_iters=warm, tag="_confirm",
        )
        trials.append(tr)
        casps = f"{tr.casps:,.0f}" if tr.casps else "-"
        flag = "  <-- spawned < requested" if tr.shortfall else ""
        print(f"    agents={a:>3}  envs={target:>6}  {tr.verdict:<10} CASPS={casps:>10}  "
              f"vram={tr.peak_vram_mib or '-'} MiB  ({tr.wall_s:.0f}s){flag}", flush=True)

        if tr.verdict == "ok":
            ceilings[a] = target
            measured[a] = tr
            if tr.peak_vram_mib:
                samples.append((target, a, tr.peak_vram_mib))
        else:
            # One backed-off retry, then give up on this level rather than
            # paying repeated large-N failures.
            retry = max(args.min_envs, int(target * args.backoff))
            print(f"    backing off to {retry}", flush=True)
            tr2 = run_trial(
                agents_per_env=a, num_envs=retry, args=args, workdir=workdir,
                iterations=iters, warmup_iters=warm, tag="_confirm2",
            )
            trials.append(tr2)
            casps = f"{tr2.casps:,.0f}" if tr2.casps else "-"
            print(f"    agents={a:>3}  envs={retry:>6}  {tr2.verdict:<10} CASPS={casps:>10}  "
                  f"({tr2.wall_s:.0f}s)", flush=True)
            if tr2.verdict == "ok":
                ceilings[a] = retry
                measured[a] = tr2
                if tr2.peak_vram_mib:
                    samples.append((retry, a, tr2.peak_vram_mib))
            else:
                ceilings[a] = None

        # Refit with the new large-N point; small-N extrapolation can drift.
        refit = fit_global_vram_model(samples)
        if refit:
            model = refit
        print("", flush=True)


