#!/usr/bin/env python3
"""Weather variants of the held-out 199-scene eval pool, on the CORRECTED TRFC model.

The pre-existing eval pools (dry / ac0p4mm / ac0p8mm) were capped at 0.8 mm purely
to dodge the TRFC Eq.(12) mu=0 cliff.  That cliff was a dimensional bug and is
fixed (tasks/fix_trfc_yr_hydroplaning_cliff.md), so the old ceiling is obsolete and
far too timid: mu only spans 1.00 -> 0.80 across it, entirely above the ~0.78 where
friction first binds on this vehicle.

Levels here are chosen to span the binding region, and to keep one cell comparable
with the paper's Table 4 "moderate wet" (AC 0.5 mm).

Usage:  PYTHONPATH=. python scripts/make_eval_weather_pools.py
"""
from __future__ import annotations

from pathlib import Path

import yaml

from src.trfc.friction_api import FrictionInput, estimate_friction

BASE = Path("configs/scene_factory/generated/eval_unseen_199scenes_dry.yaml")
OUT_DIR = Path("configs/scene_factory/generated")
MMPH_PER_MM = 2.0 / 0.3
V_REF = 13.89  # the ALL model reference speed the paper reports

# tag -> water film (mm).  0.5 mm reproduces Table 4's "moderate wet" cell.
LEVELS = {"dry": 0.0, "wet0p5mm": 0.5, "wet5mm": 5.0, "wet12mm": 12.0}


def main() -> None:
    base = yaml.safe_load(BASE.read_text())
    for tag, film in LEVELS.items():
        pool = yaml.safe_load(BASE.read_text())
        for a in pool["world"]["assignments"]:
            fr = a.setdefault("friction", {})
            fr["water_film_mm"] = float(film)
            if film <= 0.0:
                fr["precip_type"], fr["precip_intensity_mmph"] = "clear", 0.0
            else:
                fr["precip_type"] = "rain"
                fr["precip_intensity_mmph"] = round(film * MMPH_PER_MM, 3)
        mus = sorted({
            round(estimate_friction(FrictionInput(
                road_type=a["friction"]["road_type"],
                water_film_mm=float(film),
                reference_speed_mps=V_REF)).mu_eff, 4)
            for a in pool["world"]["assignments"]
        })
        out = OUT_DIR / f"eval_unseen_199scenes_{tag}.yaml"
        header = (
            f"# Held-out 199-scene eval pool, uniform water film {film} mm.\n"
            f"# Generated by scripts/make_eval_weather_pools.py -- do not hand-edit.\n"
            f"# CORRECTED TRFC model.  mu at {V_REF} m/s: {mus}\n"
            f"# Differs from the sibling pools in water_film_mm ONLY.\n"
        )
        out.write_text(header + yaml.safe_dump(pool, sort_keys=False, default_flow_style=False))
        print(f"[write] {out.name:<42} film {film:>5.1f} mm   mu {mus}")


if __name__ == "__main__":
    main()
